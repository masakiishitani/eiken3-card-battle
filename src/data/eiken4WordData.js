// 英検4級用のカード統計計算（より簡単な設定）
export const calculateEiken4CardStats = (word) => {
  let cost, attack, defense;

  // 英検4級は基礎レベルなので、より低いコストと攻撃力に設定
  const baseAttack = 2;
  const baseDefense = 2;
  const baseCost = 1;

  switch (word.partOfSpeech) {
    case "verb":
      cost = Math.max(1, baseCost + Math.floor(word.difficulty * 0.3));
      attack = Math.max(1, baseAttack + word.difficulty * 1.0);
      defense = Math.max(1, baseDefense + word.difficulty * 0.3);
      break;
    case "noun":
      cost = Math.max(1, baseCost + Math.floor(word.difficulty * 0.2));
      attack = Math.max(1, baseAttack + word.difficulty * 0.3);
      defense = Math.max(1, baseDefense + word.difficulty * 1.0);
      break;
    case "adjective":
      cost = Math.max(1, baseCost + Math.floor(word.difficulty * 0.1));
      attack = Math.max(1, baseAttack + Math.floor(word.difficulty * 0.1));
      defense = Math.max(1, baseDefense + word.difficulty * 0.7);
      break;
    case "adverb":
      cost = Math.max(1, baseCost);
      attack = Math.max(1, baseAttack + word.difficulty * 0.7);
      defense = Math.max(1, baseDefense + Math.floor(word.difficulty * 0.1));
      break;
    default:
      cost = baseCost;
      attack = baseAttack;
      defense = baseDefense;
  }

  return { ...word, cost, attack, defense };
};
