// カードの攻撃力と防御力を計算する関数
export const calculateCardStats = (word) => {
  const baseAttack = word.difficulty;
  const baseDefense = Math.min(word.word.length, 8);
  
  // 品詞による補正
  const partOfSpeechBonus = {
    verb: { attack: 2, defense: 1 },
    noun: { attack: 1, defense: 2 },
    adjective: { attack: 1, defense: 1 },
    adverb: { attack: 3, defense: 0 }
  };
  
  const bonus = partOfSpeechBonus[word.partOfSpeech] || { attack: 0, defense: 0 };
  
  return {
    ...word,
    attack: baseAttack + bonus.attack,
    defense: baseDefense + bonus.defense,
    cost: Math.ceil((baseAttack + bonus.attack) / 2) // カードのコスト
  };
};

// 品詞による特殊効果
